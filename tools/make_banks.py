#!/usr/bin/env python3
"""Turn prepared ROM images + ingested coverage into recompiled title banks.

Inputs (both produced earlier, both git-ignored):
  generated/inputs   tools/prepare_acww.py output (arm9.bin, arm7.bin,
                     arm9.toml, arm7.toml, overlays/, overlays.json)
  generated/ingest   ndsrecomp tools/ingest_coverage_manifests.py output
                     (seeds/*.toml, images/*.toml + *.bin)

For every place coverage proved code ran, this writes a bank config under
generated/banks and runs nds_recompile into generated/recomp:

  acww_arm9 / acww_arm7          main modules at their header addresses
  acww_arm9_alias_<base> ...     a main module resident at another base
                                 (ITCM, WRAM, VRAM, relocated blocks)
  acww_arm9_ov<NNN>              each overlay coverage saw resident
  coverage_arm<N>_<addr>_<sha>   runtime-only code pages from the ingest

Every bank is built with --validate-live-bytes, so a recompiled function only
runs when the guest's live bytes at that address match it exactly. That is
what makes overlapping banks (overlays sharing an address, aliases) safe.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ISA = {9: "armv5te", 7: "armv4t"}
MAIN_SHARDS = {9: 16, 7: 4}
SEED_FILE = re.compile(r"^arm(9|7)_(arm9|arm7|arm9_overlay_(\d{3}))_([0-9a-f]{8})$")


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def load_toml(path: Path) -> dict:
    with path.open("rb") as handle:
        return tomllib.load(handle)


def seeds_from(path: Path) -> list[tuple[int, str]]:
    data = load_toml(path)
    return [(int(e["addr"]), str(e["mode"])) for e in data.get("entry_point", [])]


def shards_for(size: int) -> int:
    # The runner only picks up shard files named <bank>_NN.c, so never 1.
    return max(2, min(16, (size + 0x7FFF) // 0x8000))


def write_config(path: Path, *, name: str, bank: str, cpu: int, load: int,
                 size: int, sha1: str, entries: list[tuple[int, str]],
                 overlay: dict | None = None) -> None:
    entries = sorted(set(entries))
    inside = [e for e in entries if load <= e[0] < load + size]
    if not inside:
        raise SystemExit(f"{bank}: no entry point falls inside the image")
    lines = [
        "# AUTO-GENERATED by tools/make_banks.py; do not commit.",
        "[program]",
        f"name = {toml_string(name)}",
        f"id = {toml_string(bank)}",
        f'cpu = "arm{cpu}"',
        f'isa = "{ISA[cpu]}"',
        f"load_address = 0x{load:08x}",
        f"size = 0x{size:08x}",
        f"entry_pc = 0x{inside[0][0]:08x}",
        "authoritative_entry_points = false",
        "",
        "[identity]",
        f"sha1 = {toml_string(sha1)}",
        "",
    ]
    if overlay:
        lines += ["[overlay]"] + [f"{k} = {v}" for k, v in overlay.items()] + [""]
    for addr, mode in inside:
        lines += ["[[entry_point]]", f"addr = 0x{addr:08x}",
                  f"mode = {toml_string(mode)}", 'kind = "runtime_observed"', ""]
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def plan_banks(inputs: Path, ingest: Path, work: Path) -> list[dict]:
    work.mkdir(parents=True, exist_ok=True)
    modules = {9: inputs / "arm9.bin", 7: inputs / "arm7.bin"}
    declared = {}
    header_entry = {}
    for cpu in (9, 7):
        cfg = load_toml(inputs / f"arm{cpu}.toml")["program"]
        declared[cpu] = int(cfg["load_address"])
        header_entry[cpu] = (int(cfg["entry_pc"]), "arm")
    overlays = {o["id"]: o for o in json.loads(
        (inputs / "overlays.json").read_text(encoding="utf-8"))}

    banks: list[dict] = []
    seeds_dir = ingest / "seeds"
    for seed_path in sorted(seeds_dir.glob("*.toml")):
        match = SEED_FILE.match(seed_path.stem)
        if not match:
            continue  # *_unresolved: covered by the runtime banks below
        cpu = int(match.group(1))
        overlay_id = match.group(3)
        base = int(match.group(4), 16)
        entries = seeds_from(seed_path)

        if overlay_id is not None:
            ov = overlays[int(overlay_id)]
            image = inputs / "overlays" / ov["file"]
            data = image.read_bytes()
            bank = f"acww_arm9_ov{overlay_id}"
            meta = {"id": int(overlay_id),
                    "bss_size": f"0x{ov['bss_size']:08x}",
                    "static_init_start": ov["static_init_start"],
                    "static_init_end": ov["static_init_end"]}
            name = f"ACWW ARM9 overlay {overlay_id}"
        else:
            image = modules[cpu]
            data = image.read_bytes()
            meta = None
            if base == declared[cpu]:
                bank = f"acww_arm{cpu}"
                entries.append(header_entry[cpu])
                name = f"ACWW ARM{cpu} main"
            else:
                bank = f"acww_arm{cpu}_alias_{base:08x}"
                name = f"ACWW ARM{cpu} main @ alias base 0x{base:08X}"

        config = work / f"{bank}.toml"
        write_config(config, name=name, bank=bank, cpu=cpu, load=base,
                     size=len(data), sha1=hashlib.sha1(data).hexdigest(),
                     entries=entries, overlay=meta)
        shards = (MAIN_SHARDS[cpu] if bank == f"acww_arm{cpu}"
                  else shards_for(len(data)))
        banks.append({"bank": bank, "config": config, "bin": image,
                      "shards": shards, "seeds": len(entries)})

    for config in sorted((ingest / "images").glob("*.toml")):
        image = config.with_suffix(".bin")
        if image.is_file():
            banks.append({"bank": config.stem, "config": config, "bin": image,
                          "shards": 2, "seeds": None})
    return banks


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--recompiler", type=Path, required=True,
                        help="path to nds_recompile(.exe)")
    parser.add_argument("--inputs", type=Path, default=Path("generated/inputs"))
    parser.add_argument("--ingest", type=Path, default=Path("generated/ingest"))
    parser.add_argument("--work", type=Path, default=Path("generated/banks"))
    parser.add_argument("--out", type=Path, default=Path("generated/recomp"))
    args = parser.parse_args()

    banks = plan_banks(args.inputs, args.ingest, args.work)
    if args.out.exists():
        shutil.rmtree(args.out)  # stale shards would otherwise get linked
    args.out.mkdir(parents=True)

    failures = []
    for index, spec in enumerate(banks, 1):
        cmd = [str(args.recompiler), "--config", str(spec["config"]),
               "--bin", str(spec["bin"]), "--out", str(args.out),
               "--bank", spec["bank"], "--shards", str(spec["shards"]),
               "--stable-address-shards", "--max-function-bytes", "512",
               "--validate-live-bytes"]
        result = subprocess.run(cmd, capture_output=True, text=True)
        emitted = [l for l in result.stdout.splitlines() if l.startswith("[emit] bank")]
        status = emitted[0].split(": ", 1)[1].split(" -> ")[0] if emitted else "FAILED"
        print(f"[{index:3d}/{len(banks)}] {spec['bank']}: {status}")
        if result.returncode != 0 or not emitted:
            failures.append(spec["bank"])
            sys.stderr.write(result.stdout[-2000:] + result.stderr[-2000:])

    main_banks = [b for b in banks if b["bank"].startswith("acww_")]
    print(f"\n{len(main_banks)} module/overlay banks, "
          f"{len(banks) - len(main_banks)} runtime coverage banks -> {args.out}")
    if failures:
        print("FAILED: " + ", ".join(failures))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
