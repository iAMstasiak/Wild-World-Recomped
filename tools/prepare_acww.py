#!/usr/bin/env python3
"""Verify ADME rev 1 and prepare ignored ndsrecomp main/overlay inputs.

Animal Crossing: Wild World (USA, revision 1) only. Writes, under --out:

  arm9.bin / arm7.bin            decompressed main code images
  arm9.toml / arm7.toml          nds_recompile seed configs
  overlays/arm9_overlay_NNN.*    every ARM9 overlay image + seed config
  overlays.json                  overlay inventory (addresses, sizes, hashes)
  game_header.toml               [arm9]/[arm7] tables for the project game.toml

Everything written here is derived from the ROM: keep it out of git.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import struct
from pathlib import Path

try:
    import ndspy.codeCompression as code_compression
    import ndspy.rom
except ImportError as exc:
    raise SystemExit(
        "ndspy 4.2.0 is required: py -3.12 -m pip install ndspy==4.2.0"
    ) from exc


EXPECTED_ROM_SHA1 = "77fde3e30e1e6068395d1f96ea63be569b61c351"
EXPECTED_ROM_SIZE = 32 * 1024 * 1024
EXPECTED_GAME_CODE = b"ADME"
EXPECTED_REVISION = 1          # header byte 0x1E ("ROM version")

TITLE = "Animal Crossing: Wild World (USA rev 1)"
PROGRAM_ID = "acww_adme1"

# Overlays loading at or above this address target DSi-only memory.
DS_MAIN_RAM_LIMIT = 0x02400000


def sha1(data: bytes) -> str:
    return hashlib.sha1(data).hexdigest()


def toml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def write_text(path: Path, lines: list[str]) -> None:
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def write_seed_config(
    path: Path,
    *,
    name: str,
    program_id: str,
    load_address: int,
    entry_pc: int,
    binary: bytes,
    coverage_entries: list[dict[str, object]],
) -> None:
    lines = [
        "# AUTO-GENERATED by tools/prepare_acww.py; do not commit.",
        "[program]",
        f"name = {toml_string(name)}",
        f"id = {toml_string(program_id)}",
        f"load_address = 0x{load_address:08x}",
        f"size = 0x{len(binary):08x}",
        f"entry_pc = 0x{entry_pc:08x}",
        "authoritative_entry_points = false",
        "",
        "[identity]",
        f"sha1 = {toml_string(sha1(binary))}",
        "",
        "[[entry_point]]",
        f"addr = 0x{entry_pc:08x}",
        'mode = "arm"',
        'name = "entry"',
        'kind = "rom_header"',
        "",
    ]
    for entry in coverage_entries:
        addr = int(str(entry["addr"]), 0)
        lines.extend(
            [
                "[[entry_point]]",
                f"addr = 0x{addr:08x}",
                f"mode = {toml_string(str(entry['mode']))}",
                f"name = {toml_string(f'coverage_{addr:08x}')}",
                'kind = "tier3_coverage"',
                "",
            ]
        )
    write_text(path, lines)


def write_overlay_config(
    path: Path,
    *,
    overlay_id: int,
    load_address: int,
    binary: bytes,
    bss_size: int,
    static_init_start: int,
    static_init_end: int,
) -> None:
    # Overlays have no header entry point; real roots arrive later from
    # runtime coverage recorded while this exact image was resident.
    lines = [
        "# AUTO-GENERATED by tools/prepare_acww.py; do not commit.",
        "[program]",
        f"name = {toml_string(f'{TITLE} ARM9 overlay {overlay_id}')}",
        f"id = {toml_string(f'{PROGRAM_ID}_arm9_ov{overlay_id:03d}')}",
        f"load_address = 0x{load_address:08x}",
        f"size = 0x{len(binary):08x}",
        f"entry_pc = 0x{load_address:08x}",
        "authoritative_entry_points = false",
        "",
        "[identity]",
        f"sha1 = {toml_string(sha1(binary))}",
        "",
        "[overlay]",
        f"id = {overlay_id}",
        f"bss_size = 0x{bss_size:08x}",
        f"static_init_start = 0x{static_init_start:08x}",
        f"static_init_end = 0x{static_init_end:08x}",
        "",
    ]
    write_text(path, lines)


def verify_rom(rom_bytes: bytes) -> str:
    digest = sha1(rom_bytes)
    problems = []
    if len(rom_bytes) != EXPECTED_ROM_SIZE:
        problems.append(
            f"size {len(rom_bytes):,} bytes, expected {EXPECTED_ROM_SIZE:,}"
        )
    if rom_bytes[0x0C:0x10] != EXPECTED_GAME_CODE:
        problems.append(
            f"game code {rom_bytes[0x0C:0x10]!r}, expected {EXPECTED_GAME_CODE!r}"
        )
    if rom_bytes[0x1E] != EXPECTED_REVISION:
        problems.append(
            f"revision {rom_bytes[0x1E]}, expected {EXPECTED_REVISION}"
        )
    if digest != EXPECTED_ROM_SHA1:
        problems.append(f"SHA-1 {digest}, expected {EXPECTED_ROM_SHA1}")
    if problems:
        raise SystemExit(
            "This is not the supported Animal Crossing: Wild World "
            "(USA rev 1) dump:\n  - " + "\n  - ".join(problems)
        )
    return digest


def load_coverage(path: Path | None) -> dict[str, list[dict[str, object]]]:
    if path is None:
        return {}
    coverage = json.loads(path.read_text(encoding="utf-8"))
    if coverage.get("game_sha1") != EXPECTED_ROM_SHA1:
        raise SystemExit("coverage seed identity does not match ADME rev 1")
    return coverage.get("entry_points", {})


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rom", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument(
        "--coverage",
        type=Path,
        help="optional runtime-coverage seeds (added once the game runs)",
    )
    args = parser.parse_args()

    rom_bytes = args.rom.read_bytes()
    digest = verify_rom(rom_bytes)
    coverage = load_coverage(args.coverage)

    # Raw header fields, used for the game.toml [arm9]/[arm7] tables.
    (arm9_rom_off, arm9_entry, arm9_ram, arm9_hdr_size,
     arm7_rom_off, arm7_entry, arm7_ram, arm7_size) = struct.unpack_from(
        "<8I", rom_bytes, 0x20
    )

    rom = ndspy.rom.NintendoDSRom(rom_bytes)
    arm9_compressed = bytes(rom.arm9)
    arm9 = code_compression.decompress(arm9_compressed)
    if len(arm9) < len(arm9_compressed):
        arm9 = arm9_compressed
    arm7 = bytes(rom.arm7)

    out = args.out.resolve()
    overlays_dir = out / "overlays"
    overlays_dir.mkdir(parents=True, exist_ok=True)
    (out / "arm9.bin").write_bytes(arm9)
    (out / "arm7.bin").write_bytes(arm7)

    write_seed_config(
        out / "arm9.toml",
        name=f"{TITLE} ARM9 main",
        program_id=f"{PROGRAM_ID}_arm9",
        load_address=int(rom.arm9RamAddress),
        entry_pc=int(rom.arm9EntryAddress),
        binary=arm9,
        coverage_entries=list(coverage.get("arm9", [])),
    )
    write_seed_config(
        out / "arm7.toml",
        name=f"{TITLE} ARM7",
        program_id=f"{PROGRAM_ID}_arm7",
        load_address=int(rom.arm7RamAddress),
        entry_pc=int(rom.arm7EntryAddress),
        binary=arm7,
        coverage_entries=list(coverage.get("arm7", [])),
    )

    manifest: list[dict[str, object]] = []
    table_rows: list[str] = []
    for overlay_id, overlay in sorted(rom.loadArm9Overlays().items()):
        data = bytes(overlay.data)
        if len(data) != int(overlay.ramSize):
            raise SystemExit(
                f"overlay {overlay_id} length mismatch: "
                f"{len(data)} != {overlay.ramSize}"
            )
        load = int(overlay.ramAddress)
        filename = f"arm9_overlay_{overlay_id:03d}.bin"
        (overlays_dir / filename).write_bytes(data)
        if load < DS_MAIN_RAM_LIMIT:
            write_overlay_config(
                overlays_dir / f"arm9_overlay_{overlay_id:03d}.toml",
                overlay_id=overlay_id,
                load_address=load,
                binary=data,
                bss_size=int(overlay.bssSize),
                static_init_start=int(overlay.staticInitStart),
                static_init_end=int(overlay.staticInitEnd),
            )
        manifest.append(
            {
                "id": overlay_id,
                "file": filename,
                "file_id": int(overlay.fileID),
                "load_address": f"0x{load:08x}",
                "size": len(data),
                "bss_size": int(overlay.bssSize),
                "static_init_start": f"0x{int(overlay.staticInitStart):08x}",
                "static_init_end": f"0x{int(overlay.staticInitEnd):08x}",
                "compressed_in_rom": bool(overlay.compressed),
                "compressed_size": int(overlay.compressedSize),
                "sha1": sha1(data),
            }
        )
        end = load + len(data) + int(overlay.bssSize)
        table_rows.append(
            f"  {overlay_id:3d}  0x{load:08X}-0x{end:08X}  "
            f"{len(data):>9,}  {'yes' if overlay.compressed else 'no ':>3}"
        )
    (out / "overlays.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n"
    )

    arm7_overlays = rom.loadArm7Overlays()

    header_lines = [
        "# AUTO-GENERATED by tools/prepare_acww.py: paste into game.toml.",
        "[arm9]",
        f"rom_offset = 0x{arm9_rom_off:08x}",
        f"entry_pc = 0x{arm9_entry:08x}",
        f"load_address = 0x{arm9_ram:08x}",
        f"compressed_size = 0x{len(arm9_compressed):08x}",
        f"decompressed_size = 0x{len(arm9):08x}",
        f"overlay_count = {len(manifest)}",
        "",
        "[arm7]",
        f"rom_offset = 0x{arm7_rom_off:08x}",
        f"entry_pc = 0x{arm7_entry:08x}",
        f"load_address = 0x{arm7_ram:08x}",
        f"size = 0x{arm7_size:08x}",
        "",
    ]
    write_text(out / "game_header.toml", header_lines)

    print(f"ROM verified: ADME revision 1, SHA-1 {digest}")
    print(
        f"ARM9: {len(arm9_compressed):,} bytes in ROM -> {len(arm9):,} bytes "
        f"at 0x{arm9_ram:08X} (entry 0x{arm9_entry:08X})"
    )
    print(
        f"ARM7: {len(arm7):,} bytes at 0x{arm7_ram:08X} "
        f"(entry 0x{arm7_entry:08X})"
    )
    print(f"ARM9 overlays: {len(manifest)}")
    print("   id  RAM range (incl. BSS)       size  compressed")
    for row in table_rows:
        print(row)
    print(f"ARM7 overlays: {len(arm7_overlays)}")
    print(f"Prepared inputs under {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
